def draw_polygons(mask, polygons, value):
 im=Image.fromarray((mask*255).astype('uint8'));d=ImageDraw.Draw(im)
 for p in polygons:d.polygon(p,fill=255 if value else 0)
 return np.array(im)>0

def runs(row):
 result=[];start=None
 for x,v in enumerate(list(row)+[False]):
  if v and start is None:start=x
  elif not v and start is not None:result.extend([start,x-start]);start=None
 return result

def build():
 data={};report=[]
 for key,spec in OVERRIDES.items():
  rgb=np.asarray(Image.open(ROOT/'assets'/spec['image']).convert('RGB')).astype(float)
  r,g,b=rgb[:,:,0],rgb[:,:,1],rgb[:,:,2]
  # The authored maps deliberately use warm sand/stone to distinguish walkable
  # terrain from forest, cliffs, water and lava.
  ground=(r>132)&(g>108)&(b>58)&(r>g*1.035)&(g>b*1.025)&((r-g)<74)&((g-b)<110)
  yy,xx=np.ogrid[-3:4,-3:4];disk=xx*xx+yy*yy<=9
  ground=binary_closing(ground,structure=disk)
  # Close tiny texture holes, never large terrain islands.
  holes=binary_fill_holes(ground)&~ground
  tags,n=label(holes);sizes=np.bincount(tags.ravel());small=sizes<90;small[0]=False
  ground |= small[tags]
  ground=draw_polygons(ground,spec['floors'],True)
  ground=draw_polygons(ground,spec['blocks'],False)
  ground[:10,:]=False;ground[-10:,:]=False;ground[:,:10]=False;ground[:,-10:]=False
  # A cell is ground only if most of its pixels are actually walkable.
  coarse=ground.reshape(256,CELL,384,CELL).mean(axis=(1,3))>.7
  tags,n=label(coarse);sx,sy=spec['seed'];seed=tags[sy//CELL,sx//CELL]
  if not seed:raise ValueError(f'{key}: spawn seed is not ground')
  # Only keep the connected navigable component; isolated rooftops and rocks
  # cannot become accidental destinations.
  coarse &= tags==seed
  data[key]={'cols':384,'rows':256,'cell':8,'rowRuns':[runs(row) for row in coarse]}
  report.append(f'{key}: {int(coarse.sum())} ground cells')
 (ROOT/'collision-data.js').write_text('/* Generated by tools/build-collisions.py. Ground and collision share image coordinates. */\n(function(root){const data='+json.dumps(data,separators=(',',':'))+';if(typeof module!=="undefined"&&module.exports)module.exports=data;else root.PixelCollisionData=data;})(typeof globalThis!=="undefined"?globalThis:this);\n')
 print('\n'.join(report))

if __name__=='__main__':build()
