"""Rebuild the ground-matched collision grids from the three game maps.

Optional authoring utility: Python + Pillow + NumPy + SciPy.
The shipped game uses collision-data.js directly and has no Python dependency.
The map artwork is read, never modified. Geometry overrides cover stone bridges,
stairs, and solid buildings that cannot be inferred reliably from colour alone.
"""
